#include "libft.h"

char	*ft_strdup(const char *str)
{
	int		i;
	char	*dest;
	char	*src;

	i = 0;
	src = (char *)str;
	dest = (char *)malloc(sizeof(ft_strlen(src) + 1));
	if (!dest)
		return (0);
	while (src[i])
	{
		dest[i] = src[i];
		i++;
	}
	dest[i] = '\0';
	return (dest);
}
