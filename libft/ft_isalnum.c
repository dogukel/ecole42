#include "libft.h"

int	ft_isalnum(char c)
{
	if ((c >= '0' && c <= '9') || (c >= 'a' && c <= 'z'))
		return (1);
	else if ((c >= 'A' && c <= 'Z'))
		return (1);
	return (0);
}
